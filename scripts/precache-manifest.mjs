#!/usr/bin/env node
/**
 * Generates public/precache.js after `next build` (npm runs it via `postbuild`).
 *
 * Walks the build's static output and emits the list of hashed JS/CSS chunk URLs
 * plus the build id, which the service worker imports at install time so every
 * screen — even ones never opened online — cold-starts offline. The build id
 * versions the cache, so a new deploy cleanly evicts the previous one.
 */

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const staticDir = path.join(root, ".next", "static");
const buildIdPath = path.join(root, ".next", "BUILD_ID");
const out = path.join(root, "public", "precache.js");

if (!existsSync(staticDir)) {
  console.error("  precache: .next/static not found — run `next build` first.");
  process.exit(0); // don't fail the build
}

function walk(dir) {
  const files = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

const urls = walk(staticDir)
  .filter((f) => /\.(js|css)$/.test(f))
  .map((f) => "/_next/static/" + path.relative(staticDir, f).split(path.sep).join("/"));

const buildId = existsSync(buildIdPath) ? readFileSync(buildIdPath, "utf8").trim() : "v1";

writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/precache-manifest.mjs — do not edit.\n` +
    `self.__BUILD=${JSON.stringify(buildId)};\n` +
    `self.__PRECACHE=${JSON.stringify(urls)};\n`,
);

const kb = Math.round(urls.reduce((n, u) => n + statSync(path.join(root, u.replace("/_next/", ".next/"))).size, 0) / 1024);
console.log(`  precache: ${urls.length} chunks (~${kb} KB), build ${buildId} → public/precache.js`);
